const LAB_SCENARIOS = [
  {
    id: 1,
    label: "基线提交",
    tone: COLORS.success,
    title: "A 读版本 4，更新成功并提交",
    evidence: "A: read v4 → update 1 row → commit; balance 100 → 70",
    decision: "commit：约束满足，历史可重放",
  },
  {
    id: 2,
    label: "并发冲突",
    tone: COLORS.warning,
    title: "B 仍拿着版本 4 写入",
    evidence: "B: read v4 → update 0 rows; A 已提交 v5",
    decision: "retry：拒绝旧版本覆盖，重新读取",
  },
  {
    id: 3,
    label: "部分失败",
    tone: COLORS.danger,
    title: "订单写入后流水步骤失败",
    evidence: "order insert ok → ledger insert error → transaction rollback",
    decision: "rollback：不留下无法对账的半成品",
  },
] as const;

export function Crv18Section0108ConcurrencyLab() {
  const [scenarioId, setScenarioId] = useState(1);
  const scenario =
    LAB_SCENARIOS.find((item) => item.id === scenarioId) ?? LAB_SCENARIOS[0];

  return (
    <section
      className="my-8 rounded-card border border-border bg-elevated p-5"
      data-visual-kind="crv18-section-01-08-concurrency-lab"
      aria-label="数据库并发与事务样本实验"
      aria-labelledby="crv18-section-01-08-lab-title"
    >
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <p className="text-xs font-semibold uppercase tracking-[0.18em] text-accent">
            Lab
          </p>
          <h3
            id="crv18-section-01-08-lab-title"
            className="mt-1 text-lg font-semibold text-primary"
          >
            两会话提交实验
          </h3>
          <p className="mt-1 max-w-2xl text-sm text-secondary">
            只改变一个条件，观察版本检查、事务边界和最后的处理选择。
          </p>
        </div>
        <button
          type="button"
          className="min-h-11 rounded-button border border-border px-3 py-2 text-sm text-secondary transition hover:border-accent hover:text-accent"
          onClick={() => setScenarioId(1)}
          aria-label="重置实验"
        >
          重置实验
        </button>
      </div>
      <div
        className="mt-5 grid gap-3 sm:grid-cols-3"
        role="tablist"
        aria-label="数据库场景选择"
      >
        {LAB_SCENARIOS.map((item) => {
          const selected = item.id === scenarioId;
          return (
            <button
              key={item.id}
              type="button"
              role="tab"
              aria-selected={selected}
              className={`min-h-11 rounded-button border px-3 py-2 text-left text-sm transition ${
                selected
                  ? "border-accent bg-accent/10 text-accent"
                  : "border-border text-secondary hover:border-accent hover:text-accent"
              }`}
              onClick={() => setScenarioId(item.id)}
            >
              <span className="block font-semibold">{item.label}</span>
              <span className="mt-1 block text-xs opacity-80">
                场景 {item.id}
              </span>
            </button>
          );
        })}
      </div>
      <div className="mt-4 grid gap-3 md:grid-cols-[1fr_auto]">
        <div className="rounded-card border border-border p-4">
          <div className="flex items-center gap-2">
            <span
              className="h-2.5 w-2.5 rounded-full"
              style={{ backgroundColor: scenario.tone }}
            />
            <p className="font-semibold text-primary">{scenario.title}</p>
          </div>
          <p className="mt-3 break-words font-mono text-xs text-secondary">
            {scenario.evidence}
          </p>
        </div>
        <div className="rounded-card border border-border p-4 md:min-w-64">
          <p className="text-xs font-semibold uppercase tracking-wide text-secondary">
            判定
          </p>
          <p
            className="mt-2 text-sm font-semibold"
            style={{ color: scenario.tone }}
          >
            {scenario.decision}
          </p>
        </div>
      </div>
      <p className="mt-4 text-xs text-secondary" aria-live="polite">
        当前场景：{scenario.label}；记录读版本、影响行数、角色和提交/回滚事件。
      </p>
    </section>
  );
}
