      "回归任务的主要评估指标：①MSE（均方误差）——(1/m) * sum((y_hat - y)^2)，预测值与真实值之差的平方的平均值。特点是对大误差敏感（平方放大），一个大误差的贡献远大于多个小误差。适合关注大误差的场景。②MAE（平均绝对误差）——(1/m) * sum(|y_hat - y|)，预测值与真实值之差的绝对值的平均值。特点是对异常值鲁棒（线性增长而非平方增长）。适合数据中有异常值且不希望异常值主导评估的场景。③RMSE（均方根误差）——sqrt(MSE)，MSE 的平方根。优点是与原始数据同量纲，比 MSE 更易解释。④R²（决定系数）——1 - SS_res/SS_tot，其中 SS_res 是残差平方和 sum((y-y_hat)^2)，SS_tot 是总平方和 sum((y-y_mean)^2)。R² 衡量模型解释的方差占总方差的比例，取值通常在 [0, 1]（也可能为负，表示比均值预测还差）。R² = 1 表示完美拟合，R² = 0 表示模型等同于直接预测均值。MSE 和 MAE 的区别：①对大误差的敏感度——MSE 对大误差更敏感（平方放大），一个大误差为 10 的贡献（100）等于 10 个小误差为 1 的贡献总和的 10 倍；MAE 中一个大误差为 10 的贡献（10）等于 10 个小误差为 1 的贡献总和。②对异常值的鲁棒性——MAE 对异常值更鲁棒，因为误差线性增长；MSE 中异常值的大误差被平方放大，会主导整体损失。③可解释性——MAE 直接表示平均误差大小（与原始数据同量纲），直观易懂；MSE 的量纲是原始量纲的平方，不够直观（RMSE 修正了这个问题）。④优化特性——MSE 处处可导（平方函数光滑），适合梯度优化；MAE 在误差为 0 处不可导（绝对值函数），需要特殊处理。",
