import type { ReviewChapterSlug, ReviewLevel, ReviewQuestion } from "./types";

function question(
  chapter: ReviewChapterSlug,
  suffix: number,
  level: ReviewLevel,
  prompt: string,
  answer: string,
  tags: string[],
): ReviewQuestion {
  return {
    id: `${chapter}-${suffix}`,
    chapter,
    level,
    question: prompt,
    answer,
    tags,
  };
}

