    question: "FSM 的「状态爆炸」问题是什么？行为树如何缓解这个问题？",
    answer:
      "**状态爆炸**是指当 AI 行为复杂度增加时，FSM 的状态数和转移连线急剧膨胀——N 个状态之间理论上有 N×(N-1) 种可能转移，实际项目中一个中等复杂度的 NPC 很容易就有 15+ 个状态、几十条转移线，且很多转移条件是重复的（如「被攻击」几乎从任何状态都要能转到受击/反击），维护时极难保证不遗漏转移。行为树缓解此问题的方式：① **模块化复用**——一棵子树（如「战斗子树」「巡逻子树」「逃跑子树」）可以被多个 AI 复用，不用为每个 NPC 重写转移；② **层次化组织**——通过 Selector/Sequence 嵌套自然表达优先级和顺序，如顶层是 Selector（低血量逃跑 → 发现敌人战斗 → 默认巡逻），优先级写在树的上层，不需要两两转移；③ **条件与动作分离**——条件节点可以被多个路径共享，不需要为每个状态写判断；④ **扩展方便**——新增行为通常只需加子树或调整节点顺序，不必改大量转移线。但行为树也有缺点：过于频繁的 Tick 有性能开销，复杂行为树需要规划好节点粒度，且对规划类/需要远期推理的任务不够自然（这时用 GOAP 或 Utility AI）。",
