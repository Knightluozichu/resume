      "**FSM（Finite State Machine，有限状态机）** 是游戏 AI 最基础的决策模型，在任意时刻 AI 只能处于**有限个状态中的一个**，接收到事件/满足条件时从一个状态转移到另一个状态。基本要素：① **状态（State）**——AI 可能处于的行为模式，如 Idle（待机）、Patrol（巡逻）、Chase（追击）、Attack（攻击）、Flee（逃跑）；② **转移（Transition）**——从一个状态切换到另一个状态的规则，由条件触发；③ **条件（Condition）**——布尔判断，如「发现敌人」「血量 < 30%」「攻击冷却结束」；④ **事件（Event）**——驱动状态检查的触发器，可以是每帧检查（轮询）或外部事件（被攻击、听到声音）。每个状态通常有 `OnEnter`/`OnUpdate`/`OnExit` 三个生命周期回调，分别处理进入初始化、每帧行为、退出清理。FSM 优点是简单直观、性能好、易调试；缺点是状态爆炸——状态数增多时转移关系呈指数增长，难以维护。",
